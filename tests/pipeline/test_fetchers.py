def test_gnews_maps_response_fields(
    monkeypatch: pytest.MonkeyPatch, gnews_source: dict, request_obj: CollectRequest, stub_article
) -> None:
    """실제 응답 구조를 그대로 파싱한다. country가 없는 항목도 처리한다."""
    _stub_gnews_api(monkeypatch, GNEWS_SEARCH_RESPONSE)
    stub_article()

    outcome = fetchers.fetch_gnews(gnews_source, request_obj)

    assert len(outcome.items) == 2
    first = outcome.items[0]
    # 문서 식별 기준은 언론사 원문 주소
    assert first.url.startswith("https://www.moneycontrol.com/")
    assert first.title_hint == "Wall Street's favorite bet comes undone as chips whipsaw market"
    assert first.published_at_hint == datetime(2026, 8, 2, 13, 50, 15, tzinfo=timezone.utc)
    assert first.content_type == "text/html"
    # source.country가 없는 두 번째 항목도 정상 처리
    assert outcome.items[1].url.startswith("https://finbold.com/")


def test_gnews_records_plan_limit_notices(
    monkeypatch: pytest.MonkeyPatch, gnews_source: dict, request_obj: CollectRequest, stub_article
) -> None:
    """요금제 제약으로 0건이 되면 사유가 남아야 한다. 조용히 넘어가면 원인을 못 찾는다."""
    _stub_gnews_api(monkeypatch, GNEWS_EMPTY_RESPONSE)
    stub_article()

    outcome = fetchers.fetch_gnews(gnews_source, request_obj)

    assert outcome.items == []
    assert any("12-hour delay" in n for n in outcome.notices)
    assert any("beyond 30 days" in n for n in outcome.notices)
    # 전체 건수는 있는데 받은 게 없다 -> 요금제 때문에 잘렸다는 표시
    assert outcome.skip_reasons.get("removed_by_plan_limit") == 1


def test_gnews_sends_expected_query_params(
    monkeypatch: pytest.MonkeyPatch, gnews_source: dict, stub_article
) -> None:
    """lang 기본값은 en, since는 from 파라미터로 넘어간다."""
    captured = _stub_gnews_api(monkeypatch, GNEWS_SEARCH_RESPONSE)
