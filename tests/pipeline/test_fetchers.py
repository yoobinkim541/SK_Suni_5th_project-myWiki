ARTICLE_HTML = b"<html><body><article><p>chip demand</p></article></body></html>"


class _FakeResponse:
    def __init__(self, payload: dict, status_code: int = 200) -> None:
        self._payload = payload
        self.status_code = status_code

    def json(self) -> dict:
        return self._payload


@pytest.fixture
def gnews_source() -> dict:
    return {
        "id": str(uuid4()),
        "name": "gnews - semiconductor",
        "source_type": "news",
        "config": {"provider": "gnews", "query": "semiconductor", "request_delay_sec": 0},
    }


@pytest.fixture
def request_obj() -> CollectRequest:
    return CollectRequest(workspace_id=uuid4(), source_id=uuid4())


@pytest.fixture
def stub_article(monkeypatch: pytest.MonkeyPatch):
    """기사 원문 요청을 가로챈다. (요청주소 -> 최종주소) 매핑을 넘겨 리다이렉트를 흉내낸다."""

    def install(redirects: dict[str, str] | None = None):
        mapping = redirects or {}
        calls: list[str] = []

        def fake_http_get(url: str, source: dict):
            calls.append(url)
            return ARTICLE_HTML, "text/html", 200, mapping.get(url, url)

        monkeypatch.setattr(fetchers, "_http_get", fake_http_get)
        return calls

    return install


def _stub_gnews_api(monkeypatch: pytest.MonkeyPatch, payload: dict, status_code: int = 200) -> dict:
    """httpx.get을 가로채 GNews 응답을 대신 돌려준다. 전달된 파라미터를 남긴다."""
    import httpx

    captured: dict = {}

    def fake_get(url: str, **kwargs):
        captured["url"] = url
        captured["params"] = kwargs.get("params", {})
        return _FakeResponse(payload, status_code)

    monkeypatch.setattr(httpx, "get", fake_get)
    monkeypatch.setenv("GNEWS_API_KEY", "test-key-not-real")
    return captured


