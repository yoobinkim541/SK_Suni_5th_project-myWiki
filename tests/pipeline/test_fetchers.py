ARTICLE_HTML = b"<html><body><article><p>chip demand</p></article></body></html>"


class _FakeResponse:
    def __init__(self, payload: dict, status_code: int = 200, content: bytes = b"") -> None:
        self._payload = payload
        self.status_code = status_code
        self.content = content

    def json(self) -> dict:
        return self._payload


def _zip_bytes(inner_name: str, content: bytes) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr(inner_name, content)
    return buffer.getvalue()


