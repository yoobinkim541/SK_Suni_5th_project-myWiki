def test_article_url_uses_final_redirect_target(
    monkeypatch: pytest.MonkeyPatch, gnews_source: dict, request_obj: CollectRequest, stub_article
) -> None:
    """
    구글 뉴스 RSS는 news.google.com 경유 주소를 준다. 그대로 저장하면 같은 기사가
    검색어마다 다른 문서로 쌓이므로, 리다이렉트 최종 주소를 문서 기준으로 쓴다.
    """
    _stub_gnews_api(monkeypatch, GNEWS_SEARCH_RESPONSE)
    google_link = GNEWS_SEARCH_RESPONSE["articles"][0]["url"]
    stub_article({google_link: "https://www.yna.co.kr/view/AKR20260802"})

    outcome = fetchers.fetch_gnews(gnews_source, request_obj)

    assert outcome.items[0].url == "https://www.yna.co.kr/view/AKR20260802"
