def test_zero_config_values_are_not_replaced_by_defaults() -> None:
    """
    0은 유효한 설정값이다. `conf.get(key) or default`로 읽으면 0을 넣어도
    기본값이 적용돼 요청 간격이 사라지지 않는다.
    """
    source = {"config": {"request_delay_sec": 0, "max_items": 0, "timeout_sec": 0}}

    assert fetchers._conf_number(source, "request_delay_sec", 1.0) == 0
    assert fetchers._conf_number(source, "max_items", 30) == 0
    assert fetchers._conf_number(source, "timeout_sec", 15.0) == 0
    # 키가 없을 때만 기본값
    assert fetchers._conf_number({"config": {}}, "request_delay_sec", 1.0) == 1.0


def test_zero_delay_actually_skips_sleep(monkeypatch: pytest.MonkeyPatch) -> None:
    slept: list[float] = []
    monkeypatch.setattr(fetchers.time, "sleep", lambda s: slept.append(s))

    fetchers._sleep_between_requests({"config": {"request_delay_sec": 0}})
    assert slept == []

    fetchers._sleep_between_requests({"config": {"request_delay_sec": 2}})
    assert slept == [2.0]


